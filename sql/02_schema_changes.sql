-- 02_schema_changes.sql
-- new columns and id generation. nothing here changes existing data.
-- every new column is nullable or has a default, because race_test.py inserts products
-- without knowing about them.

-- the original tables have integer primary keys with no default, so the application has
-- always had to invent ids itself. two checkouts at the same moment can invent the same one.
-- these become identity columns that start after the highest id already in use.
DO $$
DECLARE
    t record;
BEGIN
    FOR t IN
        SELECT * FROM (VALUES
            ('orders', 'order_id'),
            ('order_items', 'order_item_id'),
            ('inventory_log', 'log_id')
        ) AS v(table_name, column_name)
    LOOP
        IF NOT EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = t.table_name
              AND column_name = t.column_name
              AND is_identity = 'YES'
        ) THEN
            EXECUTE format('ALTER TABLE %I ALTER COLUMN %I ADD GENERATED BY DEFAULT AS IDENTITY',
                           t.table_name, t.column_name);
        END IF;

        EXECUTE format(
            'SELECT setval(pg_get_serial_sequence(%L, %L), greatest((SELECT max(%I) FROM %I), 1))',
            t.table_name, t.column_name, t.column_name, t.table_name);
    END LOOP;
END
$$;

-- new orders start as pending until they are paid and packed.
ALTER TABLE orders ALTER COLUMN status SET DEFAULT 'pending';

-- the audit trail gets the things an auditor would ask for first: which order caused the
-- movement, what the stock was straight after it, and who made it.
ALTER TABLE inventory_log ADD COLUMN IF NOT EXISTS order_id     integer;
ALTER TABLE inventory_log ADD COLUMN IF NOT EXISTS stock_after  integer;
ALTER TABLE inventory_log ADD COLUMN IF NOT EXISTS recorded_by  text DEFAULT current_user;

-- duplicate log rows are flagged, never deleted. an audit trail you edit after the fact
-- isn't one.
ALTER TABLE inventory_log ADD COLUMN IF NOT EXISTS is_duplicate boolean NOT NULL DEFAULT false;

-- timestamps in this database have no time zone and have always meant accra time.
-- say so explicitly, so a server set to another zone can't quietly shift them.
ALTER TABLE inventory_log ALTER COLUMN created_at SET DEFAULT (now() AT TIME ZONE 'Africa/Accra');

-- the point below which a product counts as low on stock. one default for everything for
-- now; the team can set it per product as they learn what each one needs.
ALTER TABLE products ADD COLUMN IF NOT EXISTS reorder_level integer NOT NULL DEFAULT 10;
